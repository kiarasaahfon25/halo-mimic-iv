import pandas as pd
import yaml

diagnosisFile = "diagnoses_icd-2.csv"
yaml_path = "hcup_ccs_2015_definitions_benchmark.yaml"
icd10_path = "ccs_benchmark_icd10_codes.csv"  # generated by convert_benchmark_to_icd10.py


# Load YAML definitions (ICD-9) and the converted ICD-10 codes
with open(yaml_path, "r") as f:
    definitions = yaml.safe_load(f)

icd10_benchmark = pd.read_csv(icd10_path, dtype=str)

# Load only the columns we need
diagnoses = pd.read_csv(
    diagnosisFile,
    usecols=["subject_id", "hadm_id", "icd_code", "icd_version"],
    dtype=str
)

# Standardize codes (remove decimal points and whitespace)
diagnoses["icd_code"] = (
    diagnoses["icd_code"].str.strip().str.replace(".", "", regex=False).str.upper()
)

diagnoses_icd9 = diagnoses[diagnoses["icd_version"] == "9"]
diagnoses_icd10 = diagnoses[diagnoses["icd_version"] == "10"]

results = []

for category, info in definitions.items():
    if not info.get("use_in_benchmark", False):
        continue

    icd9_codes = {
        str(code).strip().replace(".", "").upper()
        for code in info.get("codes", [])
    }
    icd10_codes = set(
        icd10_benchmark.loc[icd10_benchmark["group"] == category, "icd10_code"]
    )

    matches_icd9 = diagnoses_icd9[diagnoses_icd9["icd_code"].isin(icd9_codes)]
    matches_icd10 = diagnoses_icd10[diagnoses_icd10["icd_code"].isin(icd10_codes)]

    results.append({
        "category": category,
        "icd9_codes": len(icd9_codes),
        "icd10_codes": len(icd10_codes),
        "icd9_rows": len(matches_icd9),
        "icd10_rows": len(matches_icd10),
        "icd9_admissions": matches_icd9["hadm_id"].nunique(),
        "icd10_admissions": matches_icd10["hadm_id"].nunique(),
        "unique_patients": pd.concat(
            [matches_icd9["subject_id"], matches_icd10["subject_id"]]
        ).nunique()
    })

results_df = pd.DataFrame(results)

print(f"ICD-9 admissions: {diagnoses_icd9['hadm_id'].nunique()}")
print(f"ICD-10 admissions: {diagnoses_icd10['hadm_id'].nunique()}\n")
print(results_df.to_string(index=False))
